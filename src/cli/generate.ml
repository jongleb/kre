let client (spec : Forge.Spec.t) =
  let route (route : Forge.Spec.route) =
    let segments =
      List.filter
        (fun segment -> segment <> "")
        (String.split_on_char '/' route.path)
    in
    let path_value name =
      List.find_map
        (fun (param : Forge.Spec.param) ->
          match param.location with
          | Path when String.equal param.name name -> Some param.value
          | Path | Query _ -> None)
        route.params
    in
    let path =
      List.map
        (fun segment ->
          match (String.split_on_char ':' segment, segment) with
          | [ ""; name ], _ ->
              Option.fold
                ~none:(Printf.sprintf "%S" segment)
                ~some:(fun (value : Forge.Spec.value) ->
                  Printf.sprintf "Forge_client.Wire.segment (module %s) %s"
                    value.module_ name)
                (path_value name)
          | _, literal -> Printf.sprintf "%S" literal)
        segments
    in
    let queries =
      List.filter_map
        (fun (param : Forge.Spec.param) ->
          match param.location with
          | Path -> None
          | Query presence -> Some (param, presence))
        route.params
    in
    let arguments =
      List.filter_map
        (fun (param : Forge.Spec.param) ->
          match param.location with
          | Path -> Some ("~" ^ param.name)
          | Query _ -> None)
        route.params
      @ List.map
          (fun ((param : Forge.Spec.param), (presence : Forge.Spec.presence)) ->
            match presence with
            | Optional -> "?" ^ param.name
            | Required | Repeated -> "~" ^ param.name)
          queries
      @ Option.fold ~none:[] ~some:(fun _ -> [ "~body" ]) route.body
    in
    let unit =
      match
        ( arguments,
          List.find_opt
            (fun ((_ : Forge.Spec.param), (presence : Forge.Spec.presence)) ->
              match presence with
              | Optional -> true
              | Required | Repeated -> false)
            queries )
      with
      | [], _ | _, Some _ -> [ "()" ]
      | _ :: _, None -> []
    in
    String.concat ""
      [
        Printf.sprintf "let %s %s =\n" route.name
          (String.concat " " (arguments @ unit));
        Printf.sprintf "  Forge_client.Http.request `%s\n"
          (Dream.method_to_string route.verb);
        Printf.sprintf "    ~path:[ %s ]\n" (String.concat "; " path);
        (match queries with
        | [] -> ""
        | _ ->
            Printf.sprintf "    ~query:\n      [\n%s      ]\n"
              (String.concat ""
                 (List.map
                    (fun ( (param : Forge.Spec.param),
                           (presence : Forge.Spec.presence) ) ->
                      Printf.sprintf
                        "        Forge_client.Wire.query (module %s) \
                         Forge_shared.Presence.%s %S %s;\n"
                        param.value.module_
                        (match presence with
                        | Required -> "Required"
                        | Optional -> "Optional"
                        | Repeated -> "Repeated")
                        param.name param.name)
                    queries)));
        Option.fold ~none:""
          ~some:(fun (body : Forge.Spec.value) ->
            Printf.sprintf
              "    ~body:(Forge_client.Wire.body (module %s) body)\n"
              body.module_)
          route.body;
        Printf.sprintf "    %s\n"
          (match route.returns with
          | Unit -> "Forge_client.Wire.Unit"
          | Text -> "Forge_client.Wire.Text"
          | Raw -> "Forge_client.Wire.Raw"
          | Json value ->
              Printf.sprintf "(Forge_client.Wire.Json (module %s))"
                value.module_);
      ]
  in
  String.concat "\n"
    (Printf.sprintf
       "(* Generated by forge client from the %s controller; do not edit. *)\n"
       spec.prefix
    :: List.map route spec.routes)

let routes specs =
  String.concat ""
    (List.concat_map
       (fun (spec : Forge.Spec.t) ->
         List.map
           (fun (route : Forge.Spec.route) ->
             Printf.sprintf "%-7s %-32s %s %d\n"
               (Dream.method_to_string route.verb)
               route.path route.name
               (Dream.status_to_int route.status))
           spec.routes)
       specs)
